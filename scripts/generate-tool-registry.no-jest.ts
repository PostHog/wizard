/**
 * Writes `src/programs/warehouse-sources/registry.generated.ts` from PostHog's
 * tool catalog JSON. PostHog owns the catalog; this repo only mirrors it.
 *
 *   npx tsx scripts/generate-tool-registry.no-jest.ts <path-or-url>
 *
 * The shape is checked twice: here for the schema version, then by `pnpm
 * typecheck` (the output is typed as `ToolCatalog`) and the detector tests.
 */

import { execFileSync } from 'child_process';
import { readFile, writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const SUPPORTED_SCHEMA_VERSION = 1;
const OUTPUT = fileURLToPath(
  new URL(
    '../src/programs/warehouse-sources/registry.generated.ts',
    import.meta.url,
  ),
);

async function readCatalog(source: string): Promise<unknown> {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) {
      throw new Error(`GET ${source} returned ${response.status}`);
    }
    return await response.json();
  }
  return JSON.parse(await readFile(source, 'utf8'));
}

function assertCatalog(
  value: unknown,
): asserts value is { schema_version: number; tools: unknown[] } {
  if (typeof value !== 'object' || value === null) {
    throw new Error('Catalog is not a JSON object');
  }
  const catalog = value as Record<string, unknown>;
  if (catalog.schema_version !== SUPPORTED_SCHEMA_VERSION) {
    throw new Error(
      `Unsupported catalog schema_version ${String(
        catalog.schema_version,
      )}; this generator reads ${SUPPORTED_SCHEMA_VERSION}`,
    );
  }
  if (!Array.isArray(catalog.tools) || catalog.tools.length === 0) {
    throw new Error('Catalog has no tools');
  }
}

/** npm and pypi lead; every other ecosystem follows alphabetically. */
const LEADING_ECOSYSTEMS = ['npm', 'pypi'];

function ecosystemRank(ecosystem: string): [number, string] {
  const leading = LEADING_ECOSYSTEMS.indexOf(ecosystem);
  return [leading === -1 ? LEADING_ECOSYSTEMS.length : leading, ecosystem];
}

function compareEcosystems(a: string, b: string): number {
  const [rankA, nameA] = ecosystemRank(a);
  const [rankB, nameB] = ecosystemRank(b);
  return rankA - rankB || nameA.localeCompare(nameB);
}

/**
 * Each tool's signals in one order: env keys, then script hosts, then
 * packages by ecosystem. The registry then reads the same way whatever key
 * order the JSON arrived in.
 */
function orderSignals(tool: unknown): unknown {
  if (typeof tool !== 'object' || tool === null) return tool;
  const record = tool as Record<string, unknown>;
  const signals = record.signals as Record<string, unknown> | undefined;
  if (!signals) return tool;
  const packages = (signals.packages ?? {}) as Record<string, unknown>;
  return {
    ...record,
    signals: {
      env_key_patterns: signals.env_key_patterns,
      script_hosts: signals.script_hosts,
      packages: Object.fromEntries(
        Object.keys(packages)
          .sort(compareEcosystems)
          .map((ecosystem) => [ecosystem, packages[ecosystem]]),
      ),
    },
  };
}

async function main(): Promise<void> {
  const source = process.argv[2];
  if (!source) {
    throw new Error('Usage: generate-tool-registry.no-jest.ts <path-or-url>');
  }
  const catalog = await readCatalog(source);
  assertCatalog(catalog);

  const body = [
    '// Generated by scripts/generate-tool-registry.no-jest.ts from PostHog',
    '// products/wizard/tool-catalog.generated.json. Do not edit by hand: change',
    '// the catalog in PostHog, and the sync workflow regenerates this file.',
    "import type { ToolCatalog } from './types.js';",
    '',
    `export const TOOL_CATALOG: ToolCatalog = ${JSON.stringify({
      ...catalog,
      tools: catalog.tools.map(orderSignals),
    })};`,
    '',
  ].join('\n');

  await writeFile(OUTPUT, body);
  execFileSync('pnpm', ['exec', 'prettier', '--write', OUTPUT], {
    stdio: 'ignore',
  });
  process.stdout.write(
    `Wrote ${catalog.tools.length} tools to ${path.relative(
      process.cwd(),
      OUTPUT,
    )}\n`,
  );
}

main().catch((error: unknown) => {
  process.stderr.write(
    `${error instanceof Error ? error.message : String(error)}\n`,
  );
  process.exit(1);
});
